insert into comp_signoffs (instructor_id, line_id, tick_type, signed_by, source, reason)
select i.id, l.id, t.tick, case when t.tick = 'self' then null else 'Paper folder' end, 'scan',
       'Completed/RRCC box ticked at the top of the form in the folder (' || r.pages || ')'
from _rcc r
join instructors i on lower(i.name) = lower(r.name)
join competencies c on c.code = r.code
join competency_lines l on l.comp_id = c.id
cross join lateral (values ('self', l.needs_self), ('obs1', l.needs_obs1), ('obs2', l.needs_obs2),
                           ('assess1', l.needs_assess1), ('assess2', l.needs_assess2), ('assess3', l.needs_assess3)) as t(tick, needed)
where t.needed
on conflict (instructor_id, line_id, tick_type) do nothing;

