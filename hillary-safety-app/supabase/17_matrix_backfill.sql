insert into comp_signoffs (instructor_id, line_id, tick_type, site, signed_by, source, reason)
select i.id, l.id, t.tick, m.site, case when t.tick = 'self' then null else 'Matrix back-fill' end, 'backfill',
       'Back-filled from the competency matrix (' || m.status || '), November 2026'
from _matrix m
join instructors i on lower(i.name) = lower(m.name)
join competencies c on c.code = m.code
join competency_lines l on l.comp_id = c.id
cross join lateral (values ('self', l.needs_self), ('obs1', l.needs_obs1), ('obs2', l.needs_obs2),
                           ('assess1', l.needs_assess1), ('assess2', l.needs_assess2), ('assess3', l.needs_assess3)) as t(tick, needed)
where t.needed and (m.status = 'Competent' or t.tick in ('self','obs1','obs2'))
on conflict (instructor_id, line_id, tick_type) do nothing;

